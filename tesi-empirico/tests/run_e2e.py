"""End-to-end pipeline test on SYNTHETIC data.

Generates a clearly-labeled synthetic TED raw tree under tests/tmp/output/,
runs 03_classify -> 04_build_panel -> 05..09 with TESI_OUTPUT_DIR pointing
there (the real output/ tree is never touched), and asserts:

- parsing/cleaning rules D1, D3, C4 fire exactly on the planted records
- Z1: failed chunks -> NaN, complete chunks -> real zeros
- FX conversion matches the synthetic rates
- the CS estimator recovers the PLANTED positive effect on cyber tenders
- the placebo (generic ICT, generated with NO effect) stays near zero
- all expected figures/tables/results files exist

This validates the CODE. It says nothing about real TED data.
"""
from __future__ import annotations

